  static Post _toPost(_FeedRaw r) {
    final commentList = _buildComments(r.id, r.commentTexts);
    _commentsMap[r.id] = commentList;

    return Post(
      id: r.id,
      authorId: r.authorId,
      authorName: r.authorName,
      authorAvatarChar: r.avatarChar,
      avatarGradientColors: r.avatarColors,
      content: r.content,
      timeLabel: r.timeLabel,
      imageGradientColors: r.gradient,
      imageIcon: r.icon,
      imageLabel: r.category.toUpperCase(),
      imageHeight: r.imageHeight,
      likeCount: r.likeCount,
      commentCount: commentList.length,
      category: r.category,
      title: r.content.length > 14
          ? '${r.content.substring(0, 14)}...'
          : r.content,
      imageUrl: ImageUrls.feedImage(r.id),
      avatarUrl: ImageUrls.avatarSeed(r.avatarSeed),
    );
  }

  static List<Comment> _buildComments(String postId, List<String> texts) {
    final commenters = [
      ('咖啡控', '咖', _purple, 'coffee'),
      ('喵星人', '喵', _teal, 'cat'),
      ('穿搭女孩', '穿', _peach, 'ootd_girl'),
      ('胶片少女', '胶', _blue, 'film'),
      ('治愈系女孩', '治', _teal, 'heal'),
      ('甜心小猪', '猪', _peach, 'pig'),
      ('桌面控', '桌', _lavender, 'desk'),
      ('郊游达人', '郊', _green, 'trip'),
    ];
    final times = [
      '刚刚',
      '5分钟前',
      '10分钟前',
      '30分钟前',
      '1小时前',
      '2小时前',
      '3小时前',
      '昨天',
    ];

    return List.generate(texts.length, (i) {
      final c = commenters[i % commenters.length];
      return Comment(
        id: 'c_${postId}_$i',
        authorName: c.$1,
        authorAvatarChar: c.$2,
        avatarGradientColors: c.$3,
        avatarUrl: ImageUrls.avatarSeed(c.$4),
        content: texts[i],
        timeLabel: times[i % times.length],
      );
    });
  }
